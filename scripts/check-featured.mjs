import assert from 'node:assert/strict';
import {selectFeatured} from '../content/featured.mjs';
const day='2026-10-21';
const articles=Array.from({length:12},(_,i)=>({slug:`a${i}`,repo:`r/${i}`,category:['插畫與圖解','像素與遊戲','網頁與介面','影像與影片'][i%4],kind:'單一 Skill',image:i%2?'example.png':undefined,published:i===11?`${day}T00:00:00Z`:'2026-10-01T00:00:00Z',intro:'i',process:'p',outputs:'o',example:'e'}));
const snapshot={date:day,repositories:articles.map((a,i)=>({repo:a.repo,stars:1000+i*100,delta:i===3?null:20,observed_at_utc:`${day}T00:00:00Z`,previous_observed_at_utc:'2026-10-20T00:00:00Z'}))};
const pick=(a=articles,s=snapshot,h=[])=>selectFeatured(a,s,h);
const result=pick();
assert.equal(result.items.length,5);
assert.equal(new Set(result.items.map(a=>a.repo)).size,5);
assert.ok(new Set(result.items.map(a=>a.category)).size>=3);
for(const c of new Set(result.items.map(a=>a.category)))assert.ok(result.items.filter(a=>a.category===c).length<=2);
assert.ok(result.items.some(a=>a.slug==='a11'),'reserve a new discovery');
assert.deepEqual(pick([...articles].reverse()),result,'input order must not affect scores or choices');
assert.deepEqual(pick(articles,snapshot,[{date:day,slugs:result.items.map(a=>a.slug)}]),result,'same-day rebuild must be idempotent');
const history=[{date:'2026-10-20',slugs:result.items.map(a=>a.slug)}];
const penalized=pick(articles,snapshot,history);
for(const a of result.items){const p=penalized.ranked.find(p=>p.slug===a.slug);assert.equal(p.penalty,12);assert.equal(p.score,Number((a.score-12).toFixed(4)));}
assert.equal(result.ranked.find(a=>a.slug==='a3').factors.growth,0,'new repos must not invent daily growth');
const oldHistory=[{date:'2026-10-13',slugs:result.items.map(a=>a.slug)},{date:'2026-10-22',slugs:result.items.map(a=>a.slug)}];
assert.deepEqual(pick(articles,snapshot,oldHistory),result,'ignore history outside prior seven days');
const repeated=Array.from({length:7},(_,i)=>({date:`2026-10-${14+i}`,slugs:result.items.map(a=>a.slug)}));
assert.equal(pick(articles,snapshot,repeated).ranked.find(a=>a.slug===result.items[0].slug).penalty,36);
const slower=structuredClone(snapshot);slower.repositories[0].delta*=2;slower.repositories[0].stars+=20;slower.repositories[0].previous_observed_at_utc='2026-10-19T00:00:00Z';
assert.equal(pick(articles,slower).ranked.find(a=>a.slug==='a0').factors.growth,result.ranked.find(a=>a.slug==='a0').factors.growth,'normalize growth to a daily interval');
const badStats=structuredClone(snapshot);badStats.repositories[0].delta=-10;badStats.repositories[1].previous_observed_at_utc=null;
assert.equal(pick(articles,badStats).ranked.find(a=>a.slug==='a0').factors.growth,0);
badStats.repositories[0].archived=true;
assert.ok(!pick(articles,badStats).ranked.some(a=>a.slug==='a0'));
assert.throws(()=>pick(articles.slice(0,4)),/five verified/);
console.log('PASS: daily selection diversity, discovery slot, deterministic ties, rebuilds, exposure penalties and missing data.');
